import 'dart:convert';
import 'dart:typed_data';

/// Builds a small, valid PDF from plain text lines.
///
/// The project has no PDF package, and the manual export is a mock: a title, a
/// handful of facts and a footer. A one-page PDF with the built-in Helvetica
/// font is enough and keeps the app dependency-free. Everything is ASCII so
/// the byte offsets in the xref table stay correct.
Uint8List buildSimplePdf(
  String title,
  List<String> lines, {
  String footer = 'Generated by EcoConnect',
}) {
  const pageHeight = 842;
  const top = 790.0;
  final content = StringBuffer()
    ..writeln('BT')
    ..writeln('/F1 16 Tf')
    ..writeln('50 $top Td')
    ..writeln('22 TL')
    ..writeln('(${_escape(title)}) Tj')
    ..writeln('T*')
    ..writeln('/F1 11 Tf')
    ..writeln('17 TL');

  for (final line in lines) {
    content
      ..writeln('(${_escape(line)}) Tj')
      ..writeln('T*');
  }

  content
    ..writeln('T*')
    ..writeln('/F1 8 Tf')
    ..writeln('(${_escape(footer)}) Tj')
    ..writeln('ET');

  final stream = content.toString();
  final objects = <String>[
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 $pageHeight] '
        '/Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
    '<< /Length ${latin1.encode(stream).length} >>\nstream\n$stream'
        'endstream',
  ];

  final buffer = StringBuffer('%PDF-1.4\n');
  final offsets = <int>[];
  for (var i = 0; i < objects.length; i++) {
    offsets.add(latin1.encode(buffer.toString()).length);
    buffer
      ..writeln('${i + 1} 0 obj')
      ..writeln(objects[i])
      ..writeln('endobj');
  }

  final xrefOffset = latin1.encode(buffer.toString()).length;
  buffer
    ..writeln('xref')
    ..writeln('0 ${objects.length + 1}')
    ..writeln('0000000000 65535 f ');
  for (final offset in offsets) {
    buffer.writeln('${offset.toString().padLeft(10, '0')} 00000 n ');
  }
  buffer
    ..writeln('trailer')
    ..writeln('<< /Size ${objects.length + 1} /Root 1 0 R >>')
    ..writeln('startxref')
    ..writeln('$xrefOffset')
    ..writeln('%%EOF');

  return Uint8List.fromList(latin1.encode(buffer.toString()));
}

/// A data URL ready for `saveDataUrl`.
String pdfDataUrl(Uint8List bytes) =>
    'data:application/pdf;base64,${base64Encode(bytes)}';

String _escape(String value) => value
    // Built-in Helvetica only covers the WinAnsi range; keep the export ASCII
    // so a stray en-dash or peso sign cannot corrupt the stream.
    .replaceAll(RegExp(r'[^\x20-\x7E]'), '-')
    .replaceAll(r'\', r'\\')
    .replaceAll('(', r'\(')
    .replaceAll(')', r'\)');

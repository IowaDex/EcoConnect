import 'package:flutter/material.dart';

import '../../../core/design/eco_tokens.dart';
import '../../../core/theme/app_colors.dart';
import '../services/manual_pdf.dart';

/// The manual's one-page PDF, drawn on screen as a sheet of paper.
///
/// The lines come from [assignmentManualPdfLines], the same builder the
/// download uses, so the officer is checking the real document and not a
/// summary of it. The page scrolls inside its frame: a bulk manual can print
/// more rows than fit in a dialog.
class ManualPdfPreview extends StatelessWidget {
  const ManualPdfPreview({
    super.key,
    required this.lines,
    this.height = 300,
  });

  final List<String> lines;
  final double height;

  @override
  Widget build(BuildContext context) {
    return Container(
      height: height,
      padding: const EdgeInsets.all(10),
      decoration: BoxDecoration(
        color: const Color(0xFFEDF1ED),
        borderRadius: BorderRadius.circular(EcoRadius.md),
        border: Border.all(color: AppColors.sage),
      ),
      child: ClipRRect(
        borderRadius: BorderRadius.circular(3),
        child: Container(
          decoration: const BoxDecoration(
            color: Colors.white,
            boxShadow: [
              BoxShadow(
                color: Color(0x1A000000),
                blurRadius: 6,
                offset: Offset(0, 2),
              ),
            ],
          ),
          child: SingleChildScrollView(
            padding: const EdgeInsets.fromLTRB(18, 16, 18, 16),
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                const Text(
                  manualPdfHeading,
                  style: TextStyle(
                    fontSize: 12,
                    height: 1.3,
                    fontWeight: FontWeight.w700,
                    color: Color(0xFF1B1B1B),
                  ),
                ),
                const SizedBox(height: 6),
                Container(height: 1, color: const Color(0xFFD9DED9)),
                const SizedBox(height: 8),
                for (final line in lines)
                  if (line.trim().isEmpty)
                    const SizedBox(height: 7)
                  else
                    Padding(
                      padding: const EdgeInsets.only(bottom: 2),
                      child: Text(
                        line,
                        style: const TextStyle(
                          fontSize: 8.5,
                          height: 1.5,
                          color: Color(0xFF333333),
                        ),
                      ),
                    ),
                const SizedBox(height: 10),
                const Text(
                  'Generated by EcoConnect',
                  style: TextStyle(fontSize: 7, color: Color(0xFF8A938A)),
                ),
              ],
            ),
          ),
        ),
      ),
    );
  }
}
